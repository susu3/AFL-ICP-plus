"""Generate deterministic build inputs from the persistent protocol registry."""
import json
import re
from pathlib import Path


def generate(root):
    root = Path(root).resolve()
    config = json.loads((root / "protocols/protocols.json").read_text())
    names, declarations, rows, sources = set(), [], [], set()
    for item in config["protocols"]:
        name = item["name"]
        if name in names or not re.fullmatch(r"[A-Z][A-Z0-9_]*", name):
            raise ValueError("Duplicate/invalid active protocol")
        names.add(name)
        path = (root / item["source"]).resolve()
        if root not in path.parents or not path.is_file() or path.suffix != ".c":
            raise ValueError("Protocol source escapes build tree or is absent")
        sources.add(item["source"])
        for field, result in (("requests", "region_t"), ("responses", "unsigned int")):
            symbol = item[field]
            if not re.fullmatch(r"[a-zA-Z_][a-zA-Z0-9_]*", symbol):
                raise ValueError("Invalid adapter symbol")
            declarations.append("extern %s *%s(unsigned char *, unsigned int, unsigned int *);" % (result, symbol))
        rows.append('  {"%s", %s, %s},' % (name, item["requests"], item["responses"]))
    (root / "protocols/active_registry.inc").write_text("/* Generated by tools/registry.py. */\n" + "\n".join(declarations) + "\nstatic const aflnet_protocol_adapter_t adapters[] = {\n" + "\n".join(rows) + "\n};\n")
    (root / "protocols/active.mk").write_text("# Generated by tools/registry.py\nADAPTER_SOURCES := " + " ".join(sorted(sources)) + "\nADAPTER_OBJECTS := $(ADAPTER_SOURCES:.c=.o) protocols/registry.o\n")


if __name__ == "__main__":
    generate(Path(__file__).resolve().parent.parent)
